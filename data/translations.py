def get_text(key: str, lang: str = "te", default: str = "") -> str:
    """Safely retrieves translated string based on key and language code."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["te"])
    if key in lang_dict:
        return lang_dict[key]
    # Fallback to English if not found in selected language
    if key in TRANSLATIONS["en"]:
        return TRANSLATIONS["en"][key]
    return default or key
